import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright-chromium';
const version=JSON.parse(fs.readFileSync('content/deck-manifest.json','utf8'))[0].version;
fs.mkdirSync(`review/previews/deck-${version}`,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const page=await browser.newPage({viewport:{width:1280,height:720}});
const errors=[],external=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
try{
  await page.goto(pathToFileURL(path.resolve('presentation.html')).href+'?export=1');
  await page.evaluate(()=>document.fonts.ready);
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('DOM.enable');await cdp.send('CSS.enable');
  const {root}=await cdp.send('DOM.getDocument');
  const {nodeId}=await cdp.send('DOM.querySelector',{nodeId:root.nodeId,selector:'.deck-page.active .cover-description'});
  const {fonts}=await cdp.send('CSS.getPlatformFontsForNode',{nodeId});
  assert(fonts.some(f=>/Apple SD Gothic Neo|Malgun Gothic|NanumGothic/.test(f.familyName)&&f.glyphCount>0),'Korean glyphs must use a Korean fallback');
  const {nodeId:latinNode}=await cdp.send('DOM.querySelector',{nodeId:root.nodeId,selector:'.deck-page.active h1'});
  const {fonts:latinFonts}=await cdp.send('CSS.getPlatformFontsForNode',{nodeId:latinNode});
  assert(latinFonts.some(f=>f.familyName==='Arial'&&f.glyphCount>0),'Latin glyphs must paint with Arial');
  // Nanum remains embedded for systems without Apple/Microsoft Korean fonts.
  await page.evaluate(()=>Promise.all([400,700,800].map(w=>document.fonts.load(`${w} 24px "Nanum Gothic"`,'한글'))));
  const fontFaces=await page.evaluate(()=>[...document.fonts].filter(f=>f.family.includes('Nanum Gothic')).map(f=>({weight:f.weight,status:f.status})));
  assert.equal(fontFaces.length,3);assert(fontFaces.every(f=>f.status==='loaded'));
  await page.goto(pathToFileURL(path.resolve('presentation.html')).href+'?export=1#P006');
  await page.evaluate(()=>document.fonts.ready);
  assert(await page.locator('.deck-page.active .tour-equation .katex-html').count()>0);
  await page.keyboard.press('ArrowRight');
  assert(await page.locator('.deck-page.active .tour-equation mfrac').count()>0,'loss page derivative must render a true fraction');
  assert.equal(await page.locator('.katex-error').count(),0);
  await page.keyboard.press('ArrowRight');
  const annotations=await page.locator('.arch-detail-content annotation').allTextContents();
  assert(annotations.some(t=>t.includes('\\lVert')&&t.includes('\\rVert_2^2')),'loss norm and square must remain explicit LaTeX');
  await page.locator('.deck-page.active').screenshot({path:`review/previews/deck-${version}/math-loss-${version}.png`});
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  fs.writeFileSync('qa/full-deck/math-font-report.json',JSON.stringify({fonts,latinFonts,fontFaces,katexHtml:true,mathml:true,fraction:true,lossNorm:true,errors,externalRequests:external},null,2));
  console.log('PASS: Arial Latin / Korean fallback glyphs, embedded Nanum fallback; LaTeX inline/display, true fraction/norm; external requests 0.');
}finally{await browser.close();}
